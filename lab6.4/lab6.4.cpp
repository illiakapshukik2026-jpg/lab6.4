#include <iostream>     // Підключення бібліотеки для введення-виведення даних
#include <iomanip>      // Підключення бібліотеки для форматування виведення (setw)
#include <cstdlib>      // Підключення бібліотеки для генерації випадкових чисел (rand, srand)
#include <ctime>        // Підключення бібліотеки для роботи з часом (time)

using namespace std;    // Використання стандартного простору імен

// Функція для створення та заповнення динамічного масиву випадковими числами
void Create(double* a, const int n, const double Low, const double High) {
    for (int i = 0; i < n; i++) { // Цикл для проходу по всіх елементах масиву від 0 до n-1
        a[i] = Low + (rand() / (RAND_MAX + 1.0)) * (High - Low); // Генерація дійсного числа в діапазоні [Low, High]
    }
}

// Функція для виведення масиву на екран
void Print(double* a, const int n) {
    for (int i = 0; i < n; i++) { // Цикл для перебору всіх елементів масиву
        cout << setw(10) << fixed << setprecision(2) << a[i]; // Виведення елемента з вирівнюванням та точністю 2 знаки
    }
    cout << endl; // Перехід на новий рядок після виведення всього масиву
}

// Функція 1.1: Пошук мінімального елемента масиву
double Min(double* a, const int n) {
    double min = a[0];            // Вважаємо мінімальним перший елемент масиву
    for (int i = 1; i < n; i++) { // Цикл для перебору решти елементів від 1 до n-1
        if (a[i] < min) {         // Якщо поточний елемент менший за поточний мінімальний
            min = a[i];           // Оновлюємо значення мінімального елемента
        }
    }
    return min;                   // Повертаємо знайдене мінімальне значення
}

// Функція 1.2: Обчислення суми елементів, розташованих між першим і останнім додатними елементами
double SumBetweenPositive(double* a, const int n) {
    int first = -1;               // Індекс першого додатного елемента (початково -1)
    int last = -1;                // Індекс останнього додатного елемента (початково -1)

    for (int i = 0; i < n; i++) { // Цикл для пошуку індексів першого та останнього додатних елементів
        if (a[i] > 0) {           // Якщо елемент додатний
            if (first == -1) {    // Якщо це перший знайдений додатний елемент
                first = i;        // Запам'ятовуємо його індекс
            }
            last = i;             // Оновлюємо індекс останнього додатного елемента
        }
    }

    if (first == -1 || first == last) { // Якщо додатних менше двох або немає взагалі
        return 0.0;                       // Сума дорівнює нулю
    }

    double sum = 0.0;             // Змінна для накопичення суми
    for (int i = first + 1; i < last; i++) { // Цикл між першим і останнім додатними елементами
        sum += a[i];              // Додаємо значення елемента до суми
    }
    return sum;                   // Повертаємо обчислену суму
}

// Функція 2: Перетворення масиву (спочатку нульові елементи, потім усі інші зі збереженням відносного порядку)
void Transform(double* a, const int n) {
    double* temp = new double[n]; // Виділення пам'яті під допоміжний масив
    int k = 0;                    // Індекс для запису у допоміжний масив (починаємо з 0)

    for (int i = 0; i < n; i++) { // Перший прохід: шукаємо елементи, рівні нулю
        if (a[i] == 0) {          // Якщо елемент дорівнює нулю
            temp[k++] = a[i];     // Записуємо його у допоміжний масив і збільшуємо індекс k
        }
    }

    for (int i = 0; i < n; i++) { // Другий прохід: шукаємо всі інші елементи (не рівні нулю)
        if (a[i] != 0) {          // Якщо елемент не дорівнює нулю
            temp[k++] = a[i];     // Записуємо його у допоміжний масив і збільшуємо індекс k
        }
    }

    for (int i = 0; i < n; i++) { // Цикл для копіювання елементів назад у початковий масив
        a[i] = temp[i];           // Переносимо елемент з тимчасового масиву
    }

    delete[] temp;                // Звільнення динамічної пам'яті допоміжного масиву
}

// Головна функція програми
int main() {
    srand((unsigned)time(NULL));  // Ініціалізація генератора випадкових чисел
    int n;                        // Змінна для зберігання кількості елементів масиву
    cout << "Enter n: ";        // Виведення запиту на введення розміру
    cin >> n;                     // Зчитывання значення n з клавіатури

    double* a = new double[n];    // Виділення динамічної пам'яті під масив з n дійсних елементів
    double Low = -10.0;           // Нижня межа діапазону випадкових чисел
    double High = 10.0;           // Верхня межа діапазону випадкових чисел

    Create(a, n, Low, High);      // Виклик функції створення та заповнення масиву
    cout << "Initial array:" << endl; // Виведення повідомлення про початковий масив
    Print(a, n);                  // Виклик функції виведення масиву

    double minVal = Min(a, n);    // Виклик функції пошуку мінімального елемента
    cout << "1.1. Minimum element = " << minVal << endl; // Виведення результату мінімального елемента

    double sumBetween = SumBetweenPositive(a, n); // Виклик функції суми між додатними
    cout << "1.2. Sum between first and last positive = " << sumBetween << endl; // Виведення суми

    Transform(a, n);              // Виклик функції перетворення масиву (нули спочатку)
    cout << "Transformed array (zeros first):" << endl; // Виведення повідомлення
    Print(a, n);                  // Виклик функції виведення перетвореного масиву

    delete[] a;                   // Звільнення динамічної пам'яті основного масиву
    return 0;                     // Успішне завершення програми
}